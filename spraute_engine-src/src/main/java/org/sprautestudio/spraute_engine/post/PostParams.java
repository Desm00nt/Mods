    public static float[] rgb(String hex) {
        try {
            String h = hex.trim().replace("#", "");
            if (h.length() == 3) {
                h = "" + h.charAt(0) + h.charAt(0) + h.charAt(1) + h.charAt(1) + h.charAt(2) + h.charAt(2);
            }

            int v = Integer.parseInt(h.substring(0, 6), 16);
            return new float[]{(v >> 16 & 0xFF) / 255.0F, (v >> 8 & 0xFF) / 255.0F, (v & 0xFF) / 255.0F};
        } catch (RuntimeException var3) {
            return new float[]{1.0F, 1.0F, 1.0F};
        }
    }

    public static float[] defaults(PostParams.Param p) {
        return p.color() ? rgb(p.colorDef()) : new float[]{(float)p.def()};
    }

