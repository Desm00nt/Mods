    private final boolean[][] pixels;
    public static final int SIZE = 9;

    private Icon(String... rows) {
        this.pixels = new boolean[rows.length][];

        for (int y = 0; y < rows.length; y++) {
            this.pixels[y] = new boolean[rows[y].length()];

            for (int x = 0; x < rows[y].length(); x++) {
                this.pixels[y][x] = rows[y].charAt(x) == '#';
            }
        }
    }

    public void draw(Canvas c, int x, int y, int color) {
        for (int py = 0; py < this.pixels.length; py++) {
            boolean[] row = this.pixels[py];
            int run = -1;

            for (int px = 0; px <= row.length; px++) {
                boolean on = px < row.length && row[px];
                if (on && run < 0) {
                    run = px;
                }

                if (!on && run >= 0) {
                    c.fill(x + run, y + py, px - run, 1, color);
                    run = -1;
                }
            }
        }
    }
